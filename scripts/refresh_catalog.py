"""Regenerate src/brasskey/models/catalog.yaml from the Hugging Face API.

Curated choices (which models, which repos and quantizations, the quick-start ranking) live in
SOURCES below. Everything measurable comes from the API, never by hand: pinned revisions, file
sizes, sha256 hashes, parameter counts and the architecture read from each base model's
config.json ("measure, don't guess").

Run:  uv run python scripts/refresh_catalog.py           (needs internet; anonymous access works)
Then review the diff, run the tests, and commit the regenerated catalog.
"""

import argparse
import sys
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import yaml

from brasskey.engines.types import ModelFormat
from brasskey.models.architecture import architecture_from_config
from brasskey.models.hub import RealHub, build_artifact
from brasskey.models.types import Catalog, CatalogModel

CATALOG_PATH = Path(__file__).resolve().parents[1] / "src" / "brasskey" / "models" / "catalog.yaml"
PERMISSIVE_LICENSES = {"apache-2.0", "mit", "bsd-3-clause"}

HEADER = """\
# Brasskey model catalog. GENERATED by scripts/refresh_catalog.py from the Hugging Face API:
# revisions, file sizes, sha256 hashes and architectures are measured, not typed by hand.
# To change the curated choices, edit SOURCES in that script and regenerate.
"""


@dataclass(frozen=True)
class Source:
    id: str
    display_name: str
    family: str
    base: str  # safetensors repo with the architecture (and the bf16 artifact)
    rank: int  # quick-start ranking: higher is more capable
    gguf: tuple[str, str]  # (repo, quantization)
    mlx: str
    fp8: str | None = None
    awq: str | None = None


def qwen3(size: str, rank: int, *, gguf_quant: str = "Q4_K_M", awq: bool = True) -> Source:
    base = f"Qwen/Qwen3-{size}"
    return Source(
        id=f"qwen3-{size.lower()}",
        display_name=f"Qwen3 {size}",
        family="qwen3",
        base=base,
        rank=rank,
        gguf=(f"{base}-GGUF", gguf_quant),
        mlx=f"{base}-MLX-4bit",
        fp8=f"{base}-FP8",
        awq=f"{base}-AWQ" if awq else None,
    )


# Ungated, Apache-2.0, official Qwen repos for every format. The two smallest have only Q8_0 GGUF.
SOURCES = [
    qwen3("0.6B", 1, gguf_quant="Q8_0", awq=False),
    qwen3("1.7B", 2, gguf_quant="Q8_0", awq=False),
    qwen3("4B", 3),
    qwen3("8B", 4),
    qwen3("14B", 5),
    qwen3("30B-A3B", 6, awq=False),
    qwen3("32B", 7),
]


def build_model(hub: RealHub, source: Source) -> CatalogModel:
    base = hub.repo_info(source.base)
    if base.gated or (base.license or "").lower() not in PERMISSIVE_LICENSES:
        raise SystemExit(f"{source.base}: gated or not permissively licensed ({base.license})")
    if base.params_total is None:
        raise SystemExit(f"{source.base}: no parameter count from the API")
    config: dict[str, Any] = hub.read_config(base.repo_id, base.revision)
    parsed = architecture_from_config(config, params_total=base.params_total)

    gguf_repo, gguf_quant = source.gguf
    artifacts = [
        build_artifact(
            hub.repo_info(gguf_repo), ModelFormat.GGUF, config=None, gguf_quantization=gguf_quant
        )
    ]
    mlx_info = hub.repo_info(source.mlx)
    artifacts.append(
        build_artifact(
            mlx_info, ModelFormat.MLX, config=hub.read_config(mlx_info.repo_id, mlx_info.revision)
        )
    )
    artifacts.append(build_artifact(base, ModelFormat.SAFETENSORS, config=config))
    for repo in (source.fp8, source.awq):
        if repo:
            info = hub.repo_info(repo)
            artifacts.append(
                build_artifact(
                    info,
                    ModelFormat.SAFETENSORS,
                    config=hub.read_config(info.repo_id, info.revision),
                )
            )
    print(f"  {source.id}: {len(artifacts)} artifacts", file=sys.stderr)
    return CatalogModel(
        id=source.id,
        display_name=source.display_name,
        family=source.family,
        license=(base.license or "").lower(),
        source_repo=base.repo_id,
        quick_start_rank=source.rank,
        architecture=parsed.architecture,
        artifacts=tuple(artifacts),
        notes=parsed.notes,
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=CATALOG_PATH)
    args = parser.parse_args()

    hub = RealHub()
    print("Reading model metadata from Hugging Face...", file=sys.stderr)
    catalog = Catalog(
        generated_at=datetime.now(UTC).date(),
        models=tuple(build_model(hub, source) for source in SOURCES),
    )
    document = catalog.model_dump(mode="json", exclude_defaults=False)
    text = HEADER + yaml.safe_dump(document, sort_keys=False, width=100, allow_unicode=True)
    args.output.write_text(text, encoding="utf-8")
    print(f"Wrote {len(catalog.models)} models to {args.output}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
