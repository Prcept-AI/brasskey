"""Write the Homebrew formula for a Brasskey release, from uv.lock (ADR 0015).

    uv run python scripts/homebrew_formula.py 0.1.0a1 > ../homebrew-tap/Formula/brasskey.rb

- Resources are exactly the runtime dependencies locked in uv.lock (the versions CI tests), each
  an sdist pinned by URL and SHA-256. Packages are kept or dropped by evaluating their markers
  for macOS and Linux with Homebrew's Python; Linux-only ones go in ``on_linux``.
- Packages that homebrew-core ships as shared, bottled formulas are dependencies instead of
  resources (pydantic with pydantic-core, cryptography with cffi, certifi), as homebrew-core's own
  Python formulas do.
- The brasskey sdist URL and SHA-256 come from PyPI's JSON API for that version (or
  ``--sdist-url`` / ``--sdist-sha256``).
"""

import argparse
import json
import sys
import tomllib
import urllib.request
from collections.abc import Iterable, Mapping
from pathlib import Path
from typing import Any, cast

from packaging.markers import Marker
from packaging.utils import canonicalize_name

ROOT = Path(__file__).resolve().parents[1]
PYTHON = "python@3.15"
PYTHON_VERSION = ("3.15", "3.15.2")

# Provided by homebrew-core formulas (shared and bottled): never resources.
FROM_HOMEBREW: Mapping[str, str] = {
    "pydantic": "pydantic",
    "pydantic-core": "pydantic",
    "annotated-types": "pydantic",
    "typing-extensions": "pydantic",
    "typing-inspection": "pydantic",
    "cryptography": "cryptography",
    "cffi": "cryptography",
    "pycparser": "cryptography",
    "certifi": "certifi",
}


def _platform(sys_platform: str, system: str, machine: str) -> dict[str, str]:
    return {"sys_platform": sys_platform, "platform_system": system, "platform_machine": machine}


PLATFORMS: Mapping[str, list[dict[str, str]]] = {
    "macos": [_platform("darwin", "Darwin", "arm64"), _platform("darwin", "Darwin", "x86_64")],
    "linux": [_platform("linux", "Linux", "x86_64"), _platform("linux", "Linux", "aarch64")],
}

TEMPLATE = """\
# Generated by scripts/homebrew_formula.py in Prcept-AI/brasskey from its uv.lock; don't edit.
class Brasskey < Formula
  include Language::Python::Virtualenv

  desc "Run, benchmark and secure open models on your own hardware"
  homepage "https://github.com/Prcept-AI/brasskey"
  url "{url}"
  sha256 "{sha256}"
  license "Apache-2.0"

  depends_on "pkgconf" => :build
  depends_on "rust" => :build # for hf-xet

  depends_on "certifi" => :no_linkage
  depends_on "libyaml"
  depends_on "pydantic" => :no_linkage
  depends_on "{python}"

  on_linux do
    depends_on "cryptography" => :no_linkage # keyring's Secret Service backend
    depends_on "openssl@4" # hf-xet's native-tls
{linux_resources}  end

  pypi_packages exclude_packages: %w[{excluded}]
{resources}
  def install
    venv = virtualenv_install_with_resources(without: "hf-xet")

    resource("hf-xet").stage do
      # Build hf-xet with native-tls (the system's TLS) instead of rustls: its bundled aws-lc
      # doesn't build inside Homebrew's build environment (as in homebrew-core's hf formula).
      inreplace %w[xet_client/Cargo.toml xet_data/Cargo.toml xet_pkg/Cargo.toml],
                'default = ["rustls-tls"]', 'default = ["native-tls"]'
      venv.pip_install Pathname.pwd
    end
  end

  test do
    ENV["BRASSKEY_HOME"] = testpath/"brasskey"
    assert_match version.to_s, shell_output("#{{bin}}/brasskey --version")
    doctor = JSON.parse(shell_output("#{{bin}}/brasskey doctor --json"))
    assert doctor["ok"]
  end
end
"""


def _environment(platform: Mapping[str, str]) -> dict[str, str]:
    return {
        "python_version": PYTHON_VERSION[0],
        "python_full_version": PYTHON_VERSION[1],
        "implementation_name": "cpython",
        "platform_python_implementation": "CPython",
        "os_name": "posix",
        **platform,
    }


def _applies(marker: str | None, platform: str) -> bool:
    if not marker:
        return True
    return any(Marker(marker).evaluate(_environment(env)) for env in PLATFORMS[platform])


def load_lock(path: Path = ROOT / "uv.lock") -> dict[str, dict[str, Any]]:
    data = tomllib.loads(path.read_text(encoding="utf-8"))
    packages = cast(list[dict[str, Any]], data["package"])
    return {canonicalize_name(str(p["name"])): p for p in packages}


def _edges(
    package: Mapping[str, Any], lock: Mapping[str, Mapping[str, Any]]
) -> Iterable[tuple[str, str | None]]:
    """(dependency name, marker) of a package, including the optional deps of requested extras."""
    for dependency in cast(list[dict[str, Any]], package.get("dependencies", [])):
        name = canonicalize_name(str(dependency["name"]))
        marker = cast(str | None, dependency.get("marker"))
        yield name, marker
        for extra in cast(list[str], dependency.get("extra", [])):
            optional = cast(
                dict[str, list[dict[str, Any]]], lock[name].get("optional-dependencies", {})
            )
            for item in optional.get(extra, []):
                yield canonicalize_name(str(item["name"])), cast(str | None, item.get("marker"))


def closure(lock: Mapping[str, Mapping[str, Any]], platform: str) -> set[str]:
    """Runtime dependencies of brasskey on one platform (excluding brasskey itself)."""
    seen: set[str] = set()
    stack = ["brasskey"]
    while stack:
        current = stack.pop()
        for name, marker in _edges(lock[current], lock):
            if name not in seen and _applies(marker, platform):
                seen.add(name)
                stack.append(name)
    return seen


def resources(lock: Mapping[str, Mapping[str, Any]]) -> tuple[list[str], list[str]]:
    """(resources for every platform, Linux-only resources), sorted, minus Homebrew formulas."""
    macos = {n for n in closure(lock, "macos") if n not in FROM_HOMEBREW}
    linux = {n for n in closure(lock, "linux") if n not in FROM_HOMEBREW}
    if macos - linux:
        raise SystemExit(f"macOS-only dependencies need an on_macos block: {sorted(macos - linux)}")
    return sorted(macos & linux), sorted(linux - macos)


def _resource_block(package: Mapping[str, Any], indent: str) -> str:
    sdist = cast(dict[str, str] | None, package.get("sdist"))
    if sdist is None:
        raise SystemExit(f"{package['name']} has no sdist in uv.lock")
    algorithm, digest = sdist["hash"].split(":", 1)
    if algorithm != "sha256":
        raise SystemExit(f"{package['name']}: expected a sha256 hash, got {algorithm}")
    return (
        f'{indent}resource "{package["name"]}" do\n'
        f'{indent}  url "{sdist["url"]}"\n'
        f'{indent}  sha256 "{digest}"\n'
        f"{indent}end\n"
    )


def pypi_sdist(version: str) -> tuple[str, str]:
    url = f"https://pypi.org/pypi/brasskey/{version}/json"
    with urllib.request.urlopen(url, timeout=30) as response:
        data = cast(dict[str, Any], json.load(response))
    for file in cast(list[dict[str, Any]], data["urls"]):
        if file["packagetype"] == "sdist":
            return str(file["url"]), str(cast(dict[str, str], file["digests"])["sha256"])
    raise SystemExit(f"brasskey {version} has no sdist on PyPI")


def render(url: str, sha256: str, lock: Mapping[str, Mapping[str, Any]]) -> str:
    common, linux_only = resources(lock)
    blocks = "".join("\n" + _resource_block(lock[name], "  ") for name in common)
    linux_blocks = "".join("\n" + _resource_block(lock[name], "    ") for name in linux_only)
    excluded = " ".join(sorted(set(FROM_HOMEBREW.values())))
    return TEMPLATE.format(
        url=url,
        sha256=sha256,
        python=PYTHON,
        excluded=excluded,
        resources=blocks,
        linux_resources=linux_blocks,
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Write the Homebrew formula for a release.")
    parser.add_argument("version", help="a version published on PyPI, e.g. 0.1.0a1")
    parser.add_argument("--sdist-url", default=None)
    parser.add_argument("--sdist-sha256", default=None)
    args = parser.parse_args(argv)
    if (args.sdist_url is None) != (args.sdist_sha256 is None):
        parser.error("pass both --sdist-url and --sdist-sha256, or neither")
    url, sha256 = (
        (args.sdist_url, args.sdist_sha256)
        if args.sdist_url is not None
        else pypi_sdist(args.version)
    )
    sys.stdout.write(render(url, sha256, load_lock()))
    return 0


if __name__ == "__main__":
    sys.exit(main())
